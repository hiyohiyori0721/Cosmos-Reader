  var I18N = {
    lang: 'zh',
    dicts: dicts,
    t: function (key, vars) {
      var s = (this.dicts[this.lang] && this.dicts[this.lang][key]) ||
              (this.dicts.zh[key]) || key;
      if (vars) {
        for (var k in vars) {
          s = s.split('{' + k + '}').join(vars[k]);
        }
      }
      return s;
    },
    setLang: function (lang) {
      if (lang !== 'zh' && lang !== 'en' && lang !== 'ja') lang = 'zh';
      this.lang = lang;
      try { if (window.Storage) Storage.setSettings({ lang: lang }); } catch (_) {}
      this.applyLang();
    },
    applyLang: function () {
      var self = this;
      document.documentElement.lang = this.lang === 'zh' ? 'zh-CN' : this.lang;
      document.querySelectorAll('[data-i18n]').forEach(function (el) {
        el.textContent = self.t(el.getAttribute('data-i18n'));
      });
      document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
        el.placeholder = self.t(el.getAttribute('data-i18n-placeholder'));
      });
      document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
        el.title = self.t(el.getAttribute('data-i18n-title'));
      });
      document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
        el.setAttribute('aria-label', self.t(el.getAttribute('data-i18n-aria')));
      });
    }
  };

  window.CosmosI18n = I18N;
  // 全局快捷函数 t(key, vars)
  window.t = function (key, vars) { return I18N.t(key, vars); };
